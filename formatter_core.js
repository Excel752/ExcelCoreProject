function checkMissing(r, machine) {
  const miss = [];

  if (r.machineMismatch) return ["メモの機種と選択中の機種が一致しません"];
  if (r.quitMismatch) return ["ヤメシートの機種が選択中の機種と一致しません"];
  if (r.quitSheet) return miss;

  if (r.setting && SETTING_RATES[machine]) {
    if (r.daiban === undefined) miss.push("台番");
    if (r.start === undefined) miss.push("始め");
    if (r.diff === undefined) miss.push("差枚");
    if (r.total_end === undefined) miss.push("総回");
    if (r.chodama === undefined) miss.push("貯玉");
    return miss;
  }

  if (r.start === undefined) miss.push("始め");
  if (machine === "hokuto" && r.diff === undefined) miss.push("差枚");
  if (machine === "sao" && r.diff === undefined) miss.push("差枚");
  if (machine === "monkey" && !r.kyoen && !r.jouigo && r.diff === undefined) miss.push("差枚");
  if (machine !== "madomagi" && machine !== "tokyorev" && r.total_start === undefined) miss.push("総回（着席）");
  if (r.total_end === undefined) miss.push("総回（最終）");
  if (r.zandama === undefined) miss.push("抜け");
  if (r.cash === undefined) miss.push("現金");
  if (r.yame === undefined) miss.push("ヤメ");
  if (machine === "hokuto" && r.get === undefined) miss.push("獲得");
  if (machine === "ghoul" && !r.watari) {
    if (!r.ghoulMode) miss.push("状態（リセ or AT間）");
    if (r.ghoulThru === undefined) miss.push("スルー回数");
    if (r.ghoulPrevG === undefined) miss.push("天井消化");
  }
  if (machine === "tekken" && r.tekkenThru === undefined) miss.push("スルー回数");
  if (machine === "tokyorev") {
    if (!r.tokyorevMode) miss.push("状態（リセ / AT間天井狙い / 強演出）");
    if (r.ghoulPrevG === undefined) miss.push("天井消化（液晶ゲーム数）");
    if (r.tokyorevMode === "at" && (r.ghoulPrevG === undefined || r.ghoulPrevG < 300)) miss.push("AT間天井狙いは天井消化300以上");
  }
  if (machine === "madomagi") {
    if (!r.madomagiMode) miss.push("状態（リセ or AT間）");
    if (r.madomagiThru === undefined) miss.push("スルー回数");
    if (r.madomagiCurrentG === undefined) miss.push("現在ボナ間G");
    if (r.madomagiMode === "at" && (r.madomagiThru === 3 || r.madomagiThru === 4) && r.madomagiPrevG === undefined) {
      miss.push("括弧内の前回までAT間G");
    }
  }
  if (machine === "sao" && !r.saoCondition) miss.push("SAO条件（司会者 / ゼクシード / ダイン / ペイルライダー / 闇風 / 銃士X / デスガン / 赤アイテム / 引き戻し）");
  if (machine === "rikoriko" && !r.rikorikoState) miss.push("状態（リセ / 駆け抜け後 / 上位AT後）");
  if (machine === "rikoriko" && r.ghoulPrevG === undefined) miss.push("天井消化");
  if (machine === "karakuri2" && !r.karakuri2Type) miss.push("判定文言（赤いボール / リセ、AT後3スルー / リセ、AT後4スルー）");
  if (machine === "god" && !r.godType && !r.godMode) miss.push("前回状態（VVV/Z-ZONE/赤7/天井/GOD/前々回赤7/連荘中VVV/連荘中Z-ZONE/連荘中赤7/リセ/AT間）");
  return miss;
}


function buildHistory(r) {
  const yame = r.yame !== undefined ? r.yame : "";
  const yameLine = `${yame}#0`;
  const tokens = (r.hitsRaw || "").split("#").map(s => s.trim()).filter(s => /\d/.test(s));
  const rens = r.rens || (r.ren ? [r.ren] : []);
  if (!tokens.length) return yameLine;
  const lines = tokens.map((tok, i) => {
    const g = parseInt(tok.replace(/[^0-9]/g, ""));
    const ren = rens[i] !== undefined ? rens[i] : 1;
    return ren <= 2 ? `${g}#1#2` : `${g}#1#2###${ren - 1}`;
  });
  return [yameLine, ...lines.reverse()].join("\n");
}
function buildHistoryTensei(r) {
  const yameLine = `${r.yame !== undefined ? r.yame : ""}#0(${r.yame2 !== undefined ? r.yame2 : r.yame || ""})`;
  const hits = (r.hitsRaw || "").split("#").map(s => parseInt(s.replace(/[^0-9]/g, ""))).filter(n => !isNaN(n));
  const rens = r.rens || [];
  if (!hits.length) return yameLine;
  const lines = hits.map((g, i) => {
    const ren = rens[i] !== undefined ? rens[i] : 1;
    return ren >= 3 ? `${g}#1#2###${ren - 1}` : `${g}#1#2`;
  });
  return [yameLine, ...lines.reverse()].join("\n");
}
function buildHistoryGhoul(r) {
  const yameLine = `${r.yame !== undefined ? r.yame : ""}#0`;
  if (!r.ghoulHitsRaw) return yameLine;
  const tokens = r.ghoulHitsRaw.split("#").map(s => s.trim()).filter(s => /\d/.test(s));
  const rens = r.rens || [];
  let ri = 0;
  const lines = tokens.map(tok => {
    const g = parseInt(tok.replace(/[^0-9]/g, ""));
    const lbl = tok.replace(/[0-9]/g, "").toLowerCase();
    const hasCZ = /cz/.test(lbl);
    const hasAT = /at|エピ|引き/.test(lbl);
    let part = hasCZ && hasAT ? "#1#2" : hasCZ ? "#1" : "#2";
    let suffix = "";
    if (hasCZ && hasAT) {
      const ren = rens[ri] !== undefined ? rens[ri] : 1;
      suffix = ren >= 3 ? `###${ren - 1}` : "";
      ri++;
    } else if (hasAT) {
      const ren = rens[ri] !== undefined ? rens[ri] : 1;
      suffix = ren >= 2 ? `###${ren}` : "";
      ri++;
    } else if (!hasCZ) {
      const ren = rens[ri] !== undefined ? rens[ri] : 1;
      suffix = ren >= 2 ? `###${ren}` : "";
      ri++;
    }
    return `${g}${part}${suffix}`;
  });
  return [yameLine, ...lines.reverse()].join("\n");
}

function getRikorikoAutoKitai(state, ceilingG, thru) {
  if (!state || ceilingG === undefined || ceilingG === null || ceilingG === "") return "";
  const table = RIKORIKO_EV_TABLES[state]?.[String(thru ?? 0)];
  if (!table) return "";
  const g = Number(ceilingG);
  if (!Number.isFinite(g)) return "";

  // Only use values actually present in the supplied table.
  // Choose the greatest listed game count <= 天井消化.
  const keys = Object.keys(table).map(Number).sort((a,b) => a-b);
  const eligible = keys.filter(k => k <= g);
  if (!eligible.length) return "";
  const key = eligible[eligible.length - 1];
  return table[key];
}

function buildHistoryRikoriko(r) {
  const raw = String(r.rikorikoHitsRaw || "").trim();
  const yameLine = `${r.yame !== undefined ? r.yame : 0}#0`;
  if (!raw) return yameLine;

  const tokens = raw.split("#").map(x => x.trim()).filter(Boolean);
  const rens = r.rens || [];
  let atIndex = 0;
  const lines = tokens.map(tok => {
    const m = tok.match(/^(\d+)\s*(czat|atcz|cz|at)$/i);
    if (!m) return "";
    const g = parseInt(m[1]);
    const type = m[2].toLowerCase();
    if (type === "cz") return `${g}#1`;
    const hasCZ = type === "czat" || type === "atcz";
    const ren = rens[atIndex] !== undefined ? rens[atIndex] : 1;
    atIndex++;
    // CZの記載有無にかかわらず、連荘数から1引いた値をAT履歴に反映する。
    const suffix = ren >= 3 ? `###${ren - 1}` : "";
    return `${g}${hasCZ ? "#1#2" : "#2"}${suffix}`;
  }).filter(Boolean);

  return [yameLine, ...lines.reverse()].join("\n");
}


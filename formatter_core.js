function parseTokyoRevHits(r) {
  return (r.tokyorevHitsRaw || "").split("#").map(s => s.trim()).filter(Boolean).map(tok => {
    const m = tok.match(/^(\d+)\s*(rb|reg|れぐ|レグ|レギュラー|cz|at|らっしゅ|ラッシュ)/i);
    if (!m) return null;
    const raw = m[2].toLowerCase();
    return { g: parseInt(m[1]), type: /^(?:rb|reg|れぐ|レグ|レギュラー|cz)$/i.test(raw) ? "cz" : "at" };
  }).filter(Boolean);
}
function buildHistoryTokyoRev(r) {
  const yameLine = `${r.yame !== undefined ? r.yame : ""}#0`;
  const hits = parseTokyoRevHits(r);
  const rens = r.rens || [];
  let ai = 0;
  const lines = hits.map(hit => {
    if (hit.type === "cz") return `${hit.g}#1`;
    const ren = rens[ai] !== undefined ? rens[ai] : 1;
    ai++;
    return ren >= 3 ? `${hit.g}#2###${ren - 1}` : `${hit.g}#2`;
  });
  return [yameLine, ...lines.reverse()].join("\n");
}
function buildTokyoRevGets(r) {
  const hits = parseTokyoRevHits(r);
  if (!hits.length) return r.getRaw || "";
  const provided = (r.getRaw || "").split("#").map(x => x.trim()).filter(Boolean);
  let gi = 0;
  const out = [];
  for (const hit of hits) {
    if (hit.type === "cz") out.push("64");
    else {
      if (provided[gi] !== undefined) out.push(provided[gi]);
      gi++;
    }
  }
  while (gi < provided.length) out.push(provided[gi++]);
  return out.join("#");
}

function buildHistoryMadomagi(r) {
  const yameLine = `${r.yame !== undefined ? r.yame : ""}#0`;
  const tokens = (r.madomagiHitsRaw || "").split("#").map(s => s.trim()).filter(Boolean);
  const rens = r.rens || [];
  let atIndex = 0;

  const rbAliases = ["みたま", "reg", "レグ", "バケ", "rb"];
  const bbAliases = ["ビッグ", "びっぐ", "big", "bb"];
  // 長い表記を先に置いて、エピソードを「エピ」で途中一致させない
  const atAliases = ["エピソード", "エピボ", "エピ", "at"];
  const allAliases = [...rbAliases, ...bbAliases, ...atAliases].sort((a, b) => b.length - a.length);

  const lines = tokens.map(tok => {
    const m = tok.match(/^(\d+)\s*(.*)$/i);
    if (!m) return "";
    const g = parseInt(m[1]);
    const labels = m[2].replace(/[\s　→＞>\-ー・]+/g, "");
    const types = [];
    let pos = 0;

    // 例: bbat → [2,3] / みたまエピ → [1,3]
    while (pos < labels.length) {
      const rest = labels.slice(pos);
      const alias = allAliases.find(a => rest.toLowerCase().startsWith(a.toLowerCase()));
      if (!alias) break;
      const lower = alias.toLowerCase();
      if (rbAliases.some(a => a.toLowerCase() === lower)) types.push(1);
      else if (bbAliases.some(a => a.toLowerCase() === lower)) types.push(2);
      else if (atAliases.some(a => a.toLowerCase() === lower)) types.push(3);
      pos += alias.length;
    }
    if (!types.length) return "";

    let out = `${g}` + types.map(t => `#${t}`).join("");

    // ATを含む当たり1件につき「連荘」を1つ使用。
    // 複合表記でも例: 100bbat + 連荘3 → 100#2#3###2
    if (types.includes(3)) {
      const ren = rens[atIndex] !== undefined ? rens[atIndex] : 1;
      atIndex++;
      const atOnly = types.length === 1 && types[0] === 3;
      if (atOnly) {
        if (ren >= 2) out += `###${ren}`;
      } else if (ren >= 3) {
        out += `###${ren - 1}`;
      }
    }
    return out;
  }).filter(Boolean);

  return [yameLine, ...lines.reverse()].join("\n");
}


